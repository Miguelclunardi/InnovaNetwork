# RU (RU tab): password SSH session on the management port, "show" commands only.
# The password lives in a root file (user group) created by hand — never in config.env/git.
setup_ru_agent() {
  if [[ -z "${RU_MGMT_IP}" ]]; then remove_ru_agent; return 0; fi
  [[ "${TARGET_USER}" != root ]] || { warn "the RU agent needs a regular user"; return 0; }
  local dst="${INSTALL_DIR}/dashboard-agent" cred="${INSTALL_DIR}/state/ru-credentials" unit pre=""
  local ifc="${RU_MGMT_IFACE:-${NODE_IFACE}}"
  install -d -m 0755 -o root -g root "${dst}"
  install -m 0755 -o root -g root "${PROJECT_DIR}/dashboard/agent/ru-agent.py" "${dst}/ru-agent.py"
  install -m 0640 -o root -g "${TARGET_GROUP}" /dev/null "${dst}/ru.env"
  {
    echo "DASHBOARD_URL=http://${K3S_NODE_IP:-127.0.0.1}:${DASHBOARD_NODEPORT}"  # fixed node IP: does not change with DHCP
    echo "INGEST_TOKEN=${DASHBOARD_INGEST_TOKEN}"
    echo "RU_TARGET=${RU_SSH_USER}@${RU_MGMT_IP}"
    echo "RU_POLL_SECONDS=${RU_POLL_SECONDS}"
  } >"${dst}/ru.env"
  # extra IP of this machine on the RU management network, redone at every agent start (the "+" runs as root)
  if [[ -n "${RU_MGMT_LOCAL_CIDR}" && -n "${ifc}" ]]; then
    pre="ExecStartPre=+/usr/sbin/ip addr replace ${RU_MGMT_LOCAL_CIDR} dev ${ifc}"
  fi
  unit=$(cat <<EOU
# Gerado por open5GK3S/install.sh
[Unit]
Description=InnovaNetwork: RU state (${RU_SSH_USER}@${RU_MGMT_IP}, read only) for the dashboard
After=network-online.target k3s.service
Wants=network-online.target
ConditionPathExists=${cred}

[Service]
Type=simple
User=${TARGET_USER}
EnvironmentFile=${dst}/ru.env
EnvironmentFile=${cred}
${pre}
ExecStart=/usr/bin/python3 -u ${dst}/ru-agent.py
Restart=always
RestartSec=15

[Install]
WantedBy=multi-user.target
EOU
)
  if [[ "$(cat "${RU_UNIT_FILE}" 2>/dev/null)" != "${unit}" ]]; then
    printf '%s\n' "${unit}" >"${RU_UNIT_FILE}"; systemctl daemon-reload
  fi
  systemctl enable open5gs-k3s-ru.service >/dev/null 2>&1
  if [[ ! -s "${cred}" ]]; then
    warn "RU tab: the RU password file is missing. Create it with (use the real passwords):"
    warn "  printf 'RU_PASS=%s\\nRU_ENABLE=%s\\n' 'SSH_PASSWORD' 'ENABLE_PASSWORD' | sudo install -m 0640 -g ${TARGET_GROUP} /dev/stdin ${cred}"
    warn "  and then: sudo systemctl restart open5gs-k3s-ru"
    return 0
  fi
  chown root:"${TARGET_GROUP}" "${cred}"; chmod 0640 "${cred}"
  systemctl restart open5gs-k3s-ru.service
  ok "RU tab: agent active (${RU_SSH_USER}@${RU_MGMT_IP} via ${ifc}${RU_MGMT_LOCAL_CIDR:+, local IP ${RU_MGMT_LOCAL_CIDR}}; journalctl -u open5gs-k3s-ru)"
}

