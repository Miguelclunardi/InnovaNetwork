  else
    step_packages
    step_modules
    step_sysctl
    step_host_profile
    step_stable_netif
    step_k3s
    step_helm
  fi
  step_charts
  step_ran_link
  step_deploy_core
  step_subscribers
  step_deploy_ueransim
  step_dashboard
  step_boot_heal
  step_user_kubeconfig
  final_summary
}

