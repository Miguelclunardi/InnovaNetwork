  fi
  if ${KCTX_NOT_CURRENT}; then
    warn "your current context was kept; to use this cluster: kubectl config use-context ${KCTX}"
  fi
  if is_true "${SHELL_EXTRAS}"; then
    setup_user_bashrc
    if ${BASHRC_CHANGED}; then ok "alias 'k' and kubectl completion in ${TARGET_HOME}/.bashrc (open a new terminal)"; fi
  fi
  # real test as the user (no sudo, no KUBECONFIG)
  if su - "${TARGET_USER}" -s /bin/bash -c 'env -u KUBECONFIG kubectl get nodes' &>/dev/null; then
    ok "'kubectl get nodes' works as ${TARGET_USER} without sudo"
  else
