# Files created as root (logs, values) go back to the real user
fix_ownership() {
  [[ -n "${TARGET_USER:-}" && "${TARGET_USER}" != "root" ]] || return 0
  chown -R "${TARGET_USER}:${TARGET_GROUP}" "${LOG_DIR}" "${GENERATED_DIR}" 2>/dev/null || true
}

