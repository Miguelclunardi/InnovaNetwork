#!/usr/bin/env bash
# =============================================================================
#  install.sh — installs k3s + Helm + Open5GS (5G SA) + UERANSIM on a single
#  Ubuntu 24.04 node (desktop or server). Idempotent: it can run many times;
#  it only applies what changed in config.env.
#
#  Usage:
#    sudo ./install.sh                 # full installation
#    sudo ./install.sh --deploy-only   # only (re)generates the values and runs helm upgrade
#    sudo ./install.sh --dashboard-only  # only the dashboard (does not touch the core or the gNB)
#    CONFIG=other.env sudo -E ./install.sh
#
#  The log goes automatically to logs/install.log (no need for "| tee").
# =============================================================================
set -Eeuo pipefail
source "$(dirname "$(readlink -f "$0")")/scripts/lib/common.sh"
trap 'err "failed at line ${LINENO}: ${BASH_COMMAND}"' ERR

DEPLOY_ONLY=false
DASHBOARD_ONLY=false
usage() { sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0; }
for a in "$@"; do
  case "$a" in
    --deploy-only) DEPLOY_ONLY=true ;;
    --dashboard-only) DASHBOARD_ONLY=true ;;
    -h|--help) usage ;;
    *) die "unknown option: $a" ;;
  esac
done

# ----------------------------------------------------------------------------
#  1. Packages
# ----------------------------------------------------------------------------
step_packages() {
  step "System packages"
  local pkgs=(curl ca-certificates git iproute2 iptables kmod lksctp-tools tar gzip coreutils bash-completion) missing=()
  local p
  for p in "${pkgs[@]}"; do dpkg -s "$p" &>/dev/null || missing+=("$p"); done
  if (( ${#missing[@]} )); then
    info "installing: ${missing[*]}"
    DEBIAN_FRONTEND=noninteractive apt-get update -qq
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${missing[@]}" >/dev/null
  fi
  ok "dependencies present"
}

# ----------------------------------------------------------------------------
#  2. Kernel modules (SCTP for N2/NGAP, TUN for UPF/UE, bridge for the CNI)
# ----------------------------------------------------------------------------
step_modules() {
  step "Kernel modules"
  if ! modinfo sctp &>/dev/null; then
    if is_true "${AUTO_INSTALL_MODULES_EXTRA}"; then
      info "sctp module missing in kernel $(uname -r); installing linux-modules-extra"
      DEBIAN_FRONTEND=noninteractive apt-get update -qq
      DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "linux-modules-extra-$(uname -r)" >/dev/null \
        || die "could not install linux-modules-extra-$(uname -r). Use a 'generic' kernel."
    else
      die "sctp module unavailable and AUTO_INSTALL_MODULES_EXTRA=false"
    fi
  fi
  local mods=(sctp tun br_netfilter overlay) m
  printf '%s\n' "# Gerado por open5GK3S/install.sh" "${mods[@]}" >"${MODULES_FILE}"
  for m in "${mods[@]}"; do modprobe "$m" || die "failed to load module $m"; done
  ok "loaded and persisted in ${MODULES_FILE}: ${mods[*]}"
  if command -v checksctp &>/dev/null; then
    checksctp &>/dev/null && ok "SCTP working (checksctp)" || warn "checksctp failed"
  fi
}

# ----------------------------------------------------------------------------
#  3. sysctl
# ----------------------------------------------------------------------------
step_sysctl() {
  step "sysctl parameters"
  cat >"${SYSCTL_FILE}" <<'EOF'
# Generated by InnovaNetwork install.sh
# IPv4 forwarding (pods, UPF/N6 NAT)
net.ipv4.ip_forward = 1
# Bridge traffic going through iptables (kube-proxy / flannel)
net.bridge.bridge-nf-call-iptables = 1
net.bridge.bridge-nf-call-ip6tables = 1
# Many pods (one per NF) => more inotify
fs.inotify.max_user_instances = 1024
fs.inotify.max_user_watches = 524288
# Larger buffers for GTP-U/SCTP
net.core.rmem_max = 8388608
net.core.wmem_max = 8388608
EOF
  sysctl -q -p "${SYSCTL_FILE}" >/dev/null
  ok "applied ${SYSCTL_FILE}"
}

# ----------------------------------------------------------------------------
#  4. Environment-specific settings (desktop x server)
# ----------------------------------------------------------------------------
step_host_profile() {
  step "Settings of the '${DETECTED_PROFILE}' profile"
  if ${HAS_NM}; then
    # Without it NetworkManager tries to manage cni0/flannel/veth and breaks the pod network
    local content
    local devs="interface-name:cni0;interface-name:flannel*;interface-name:veth*"
    if [[ "${NODE_IP_MODE}" == stable ]]; then devs+=";interface-name:${STABLE_IFACE}"; fi
    content=$'# Gerado por open5GK3S/install.sh\n[keyfile]\nunmanaged-devices='"${devs}"$'\n'
    if [[ ! -f "${NM_CONF_FILE}" ]] || [[ "$(cat "${NM_CONF_FILE}")"$'\n' != "${content}" ]]; then
      mkdir -p "$(dirname "${NM_CONF_FILE}")"
      printf '%s' "${content}" >"${NM_CONF_FILE}"
      systemctl reload NetworkManager || true
    fi
    ok "NetworkManager ignora cni0/flannel*/veth*$([[ "${NODE_IP_MODE}" == stable ]] && echo "/${STABLE_IFACE}" || true)"
  else
    info "NetworkManager inactive (typical of server/netplan+networkd) — nothing to do"
  fi

  if ${UFW_ACTIVE}; then
    if is_true "${CONFIGURE_UFW}"; then
      ufw allow from "${K3S_CLUSTER_CIDR}" comment 'open5gs-k3s pods' >/dev/null
      ufw allow from "${K3S_SERVICE_CIDR}" comment 'open5gs-k3s services' >/dev/null
      ufw route allow from "${K3S_CLUSTER_CIDR}" comment 'open5gs-k3s pods' >/dev/null
      ufw route allow to "${K3S_CLUSTER_CIDR}" comment 'open5gs-k3s pods' >/dev/null
      if is_true "${WEBUI_ENABLED}"; then ufw allow "${WEBUI_NODEPORT}/tcp" comment 'open5gs-k3s webui' >/dev/null; fi
      if is_true "${DASHBOARD_ENABLED}"; then ufw allow "${DASHBOARD_NODEPORT}/tcp" comment 'open5gs-k3s dashboard' >/dev/null; fi
      if is_true "${EXPOSE_RAN}"; then ufw allow 2152/udp comment 'open5gs-k3s N3' >/dev/null; fi
      ok "UFW rules applied (cluster CIDRs, WebUI$(is_true "${EXPOSE_RAN}" && echo ', N3' || true))"
      if is_true "${EXPOSE_RAN}"; then warn "UFW does not filter SCTP by port: make sure SCTP/38412 is not blocked"; fi
    else
      warn "UFW active and CONFIGURE_UFW=false: it may block pod traffic"
    fi
  fi

  if ${HAS_FIREWALLD}; then
    if is_true "${CONFIGURE_FIREWALLD}"; then
      # k3s recommendation: pod and service networks in the trusted zone
      local fw=(--zone=trusted --add-source="${K3S_CLUSTER_CIDR}" --add-source="${K3S_SERVICE_CIDR}")
      firewall-cmd -q --permanent "${fw[@]}" 2>/dev/null || true
      if is_true "${WEBUI_ENABLED}"; then firewall-cmd -q --permanent --add-port="${WEBUI_NODEPORT}/tcp" 2>/dev/null || true; fi
      if is_true "${DASHBOARD_ENABLED}"; then firewall-cmd -q --permanent --add-port="${DASHBOARD_NODEPORT}/tcp" 2>/dev/null || true; fi
      if is_true "${EXPOSE_RAN}"; then
        firewall-cmd -q --permanent --add-port=38412/sctp --add-port=2152/udp 2>/dev/null || true
      fi
      firewall-cmd -q --reload
      firewall-cmd -q --zone=trusted --query-source="${K3S_CLUSTER_CIDR}" \
        || die "firewalld: could not add ${K3S_CLUSTER_CIDR} to the trusted zone"
      ok "firewalld: ${K3S_CLUSTER_CIDR} and ${K3S_SERVICE_CIDR} in the trusted zone$(is_true "${WEBUI_ENABLED}" && echo ", port ${WEBUI_NODEPORT}/tcp" || true)"
    else
      warn "firewalld active and CONFIGURE_FIREWALLD=false: direct traffic between pods (UE<->gNB, N3) will be rejected"
    fi
  fi

  if ${HAS_DOCKER}; then
    warn "Docker active: it sets the iptables FORWARD=DROP policy. k3s/flannel creates its own"
    warn "rules for ${K3S_CLUSTER_CIDR}, but if pods lose the network see the 'Docker' section of the troubleshooting guide."
  fi
  if ! ${HAS_AVX} && [[ -z "${MONGODB_IMAGE_REPOSITORY}" ]]; then
    warn "CPU without AVX: the default MongoDB image (8.x) does NOT run. Set MONGODB_IMAGE_* to a 4.4 version."
  fi
  if (( MEM_MB < 3500 )); then warn "low RAM (${MEM_MB} MiB). Recommended >= 4 GiB."; fi
  if (( CPUS < 2 )); then warn "only ${CPUS} vCPU. Recommended >= 2."; fi
  if (( $(swapon --show --noheadings 2>/dev/null | wc -l) > 0 )); then info "swap active (k3s tolerates it; nothing to do)"; fi
}

# ----------------------------------------------------------------------------
#  4b. Stable node interface (NODE_IP_MODE=stable)
#  k3s stores the node-ip in its config; if the host IP changes (DHCP, Wi-Fi x cable,
#  another network) k3s does not start. A dummy interface with a fixed private IP, created
#  at every boot before k3s, makes the cluster independent of the physical network.
#  The way out to the internet (N6) still follows the default route, whatever it is.
# ----------------------------------------------------------------------------
step_stable_netif() {
  step "Stable node interface (NODE_IP_MODE=${NODE_IP_MODE})"
  if [[ "${NODE_IP_MODE}" != stable ]]; then
    if [[ -f "${NETIF_UNIT_FILE}" ]]; then
      systemctl disable --now open5gs-k3s-netif.service >/dev/null 2>&1 || true
      rm -f "${NETIF_UNIT_FILE}" "${K3S_DROPIN_FILE}"
      systemctl daemon-reload
      ok "stable interface removed; k3s uses ${K3S_NODE_IFACE} (${K3S_NODE_IP})"
    else
      info "k3s uses the physical interface ${K3S_NODE_IFACE} (${K3S_NODE_IP}) — sensitive to IP changes"
    fi
    return 0
  fi
  local unit dropin changed=false
  unit=$(cat <<EOU
# Generated by InnovaNetwork install.sh
[Unit]
Description=InnovaNetwork: stable k3s node interface (${STABLE_IFACE} ${STABLE_IP}), independent of DHCP
Before=k3s.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/bin/sh -c 'ip link show ${STABLE_IFACE} >/dev/null 2>&1 || ip link add ${STABLE_IFACE} type dummy; ip addr replace ${STABLE_IP}/32 dev ${STABLE_IFACE}; ip link set ${STABLE_IFACE} up'

[Install]
WantedBy=multi-user.target
EOU
)
  dropin=$'# Generated by InnovaNetwork install.sh
[Unit]
Requires=open5gs-k3s-netif.service
After=open5gs-k3s-netif.service'
  if [[ "$(cat "${NETIF_UNIT_FILE}" 2>/dev/null)" != "${unit}" ]]; then
    printf '%s
' "${unit}" >"${NETIF_UNIT_FILE}"; changed=true
  fi
  if [[ "$(cat "${K3S_DROPIN_FILE}" 2>/dev/null)" != "${dropin}" ]]; then
    mkdir -p "$(dirname "${K3S_DROPIN_FILE}")"
    printf '%s
' "${dropin}" >"${K3S_DROPIN_FILE}"; changed=true
  fi
  if ${changed}; then systemctl daemon-reload; fi
  systemctl enable open5gs-k3s-netif.service >/dev/null 2>&1
  # 'restart' re-applies the IP/name if they changed in the config
  if ${changed}; then systemctl restart open5gs-k3s-netif.service; else systemctl start open5gs-k3s-netif.service; fi
  ip -4 -o addr show dev "${STABLE_IFACE}" 2>/dev/null | grep -q " ${STABLE_IP}/" \
    || die "could not create ${STABLE_IFACE} with ${STABLE_IP}"
  ok "${STABLE_IFACE} = ${STABLE_IP} (recreated at every boot before k3s)"
  if is_true "${EXPOSE_RAN}"; then
    warn "EXPOSE_RAN=true: the external gNB uses the physical IP ${NODE_IP}; if it changes, run 'sudo ./install.sh --deploy-only'"
  fi
}

# ----------------------------------------------------------------------------
#  5. k3s
# ----------------------------------------------------------------------------
step_k3s() {
  step "k3s ${K3S_VERSION}"
  local cfg restart=false
  cfg=$(
    echo "# Generated by InnovaNetwork install.sh from config.env"
    echo "write-kubeconfig-mode: \"0600\"   # root only; the user gets ~/.kube/open5gs-k3s.yaml"
    echo "node-ip: \"${K3S_NODE_IP}\"   # NODE_IP_MODE=${NODE_IP_MODE}"
    echo "flannel-iface: \"${K3S_NODE_IFACE}\""
    echo "cluster-cidr: \"${K3S_CLUSTER_CIDR}\""
    echo "service-cidr: \"${K3S_SERVICE_CIDR}\""
    echo "disable:"
    echo "  - traefik"
    echo "# ~15 images downloaded at the same time: the default kubelet limit (5 QPS) causes 'pull QPS exceeded'"
    echo "kubelet-arg:"
    echo "  - \"registry-qps=20\""
    echo "  - \"registry-burst=40\""
  )
  mkdir -p "$(dirname "${K3S_CONFIG_FILE}")"
  if [[ -f "${K3S_CONFIG_FILE}" && "$(cat "${K3S_CONFIG_FILE}")" != "${cfg}" ]] \
     && [[ "$(strip_comments <"${K3S_CONFIG_FILE}")" == "$(strip_comments <<<"${cfg}")" ]]; then
    printf '%s\n' "${cfg}" >"${K3S_CONFIG_FILE}"   # only comments changed: no k3s restart
  fi
  if [[ ! -f "${K3S_CONFIG_FILE}" ]] || [[ "$(cat "${K3S_CONFIG_FILE}")" != "${cfg}" ]]; then
    if [[ -f "${K3S_CONFIG_FILE}" ]] && grep -q "cluster-cidr" "${K3S_CONFIG_FILE}" \
       && ! grep -q "\"${K3S_CLUSTER_CIDR}\"" "${K3S_CONFIG_FILE}"; then
      warn "K3S_CLUSTER_CIDR changed on an existing cluster: that requires './uninstall.sh --k3s' first."
    fi
    printf '%s\n' "${cfg}" >"${K3S_CONFIG_FILE}"
    restart=true
  fi

  local installed="" sig_file="${INSTALL_DIR}/state/k3s.sig" sig
  sig="${K3S_VERSION} ${K3S_EXTRA_ARGS[*]}"
  if command -v k3s &>/dev/null; then installed=$(k3s --version 2>/dev/null | awk 'NR==1{print $3}'); fi
  if [[ "${installed}" != "${K3S_VERSION}" ]] || [[ "$(cat "${sig_file}" 2>/dev/null)" != "${sig}" ]]; then
    info "installing k3s ${K3S_VERSION} (current: ${installed:-none})"
    curl -fsSL --retry 5 --retry-delay 3 --retry-all-errors --connect-timeout 15 https://get.k3s.io -o "${INSTALL_DIR}/state/get-k3s.sh"
    INSTALL_K3S_VERSION="${K3S_VERSION}" INSTALL_K3S_EXEC="server ${K3S_EXTRA_ARGS[*]}" \
      retry sh "${INSTALL_DIR}/state/get-k3s.sh" >/dev/null
    echo "${sig}" >"${sig_file}"
    restart=false
  elif ${restart}; then
    info "k3s config changed; restarting"
    systemctl restart k3s
  fi
  systemctl enable --now k3s >/dev/null 2>&1 || true

  info "waiting for the Kubernetes API..."
  local t=0
  until k3s_ready; do
    (( t += 3 )); (( t < 300 )) || die "k3s API did not answer within 300s (journalctl -u k3s)"
    sleep 3
  done
  # k3s applies the system manifests asynchronously: wait for them to exist before the rollout
  local d
  for d in coredns local-path-provisioner; do
    t=0
    until kc -n kube-system get "deploy/${d}" &>/dev/null; do
      (( t += 3 )); (( t < 300 )) || die "deploy/${d} was not created by k3s within 300s"
      sleep 3
    done
  done
  kc wait --for=condition=Ready node --all --timeout=300s >/dev/null
  kc -n kube-system rollout status deploy/coredns --timeout=300s >/dev/null
  kc -n kube-system rollout status deploy/local-path-provisioner --timeout=300s >/dev/null
  ok "k3s $(k3s --version | awk 'NR==1{print $3}') ready; node $(kc get nodes -o jsonpath='{.items[0].metadata.name}') Ready"
  if [[ -x /usr/local/bin/kubectl && ! -L /usr/local/bin/kubectl ]]; then
    info "a separate kubectl already exists in /usr/local/bin (not replaced); use 'sudo k3s kubectl' or KUBECONFIG=${KUBECONFIG_PATH}"
  fi
}

# ----------------------------------------------------------------------------
#  6. Helm
# ----------------------------------------------------------------------------
step_helm() {
  step "Helm"
  find_helm
  local cur=""
  [[ -n "${HELM_BIN}" ]] && cur=$("${HELM_BIN}" version --template '{{.Version}}' 2>/dev/null || true)
  # Installs the pinned helm if: there is no helm; ours is another version; or the
  # system one is not v3 (Helm 4 does not accept a post-renderer as an executable)
  if [[ -z "${HELM_BIN}" ]] || \
     [[ "${HELM_BIN}" == "${INSTALL_DIR}/bin/helm" && "${cur}" != "${HELM_VERSION}" ]] || \
     [[ "${cur}" != v3.* ]]; then
    info "installing helm ${HELM_VERSION} in ${INSTALL_DIR}/bin (link in /usr/local/bin/helm)"
    local tmp arch; tmp=$(mktemp -d)
    case "$(uname -m)" in
      x86_64) arch=amd64 ;; aarch64|arm64) arch=arm64 ;;
      *) die "architecture $(uname -m) not supported by the helm download" ;;
    esac
    curl -fsSL --retry 5 --retry-delay 3 --retry-all-errors --connect-timeout 15 "https://get.helm.sh/helm-${HELM_VERSION}-linux-${arch}.tar.gz" -o "${tmp}/helm.tgz"
    curl -fsSL --retry 5 --retry-delay 3 --retry-all-errors --connect-timeout 15 "https://get.helm.sh/helm-${HELM_VERSION}-linux-${arch}.tar.gz.sha256sum" -o "${tmp}/helm.sha"
    (cd "${tmp}" && echo "$(awk '{print $1}' helm.sha)  helm.tgz" | sha256sum -c --quiet) || die "invalid helm checksum"
    tar xzf "${tmp}/helm.tgz" -C "${tmp}"
    install -D -m 0755 "${tmp}/linux-${arch}/helm" "${INSTALL_DIR}/bin/helm"
    rm -rf "${tmp}"
    [[ -e /usr/local/bin/helm ]] || ln -s "${INSTALL_DIR}/bin/helm" /usr/local/bin/helm
    HELM_BIN="${INSTALL_DIR}/bin/helm"
  fi
  ok "helm $("${HELM_BIN}" version --template '{{.Version}}') (${HELM_BIN})"
}

# ----------------------------------------------------------------------------
#  7. Gradiant charts (git, pinned ref) + dependencies
# ----------------------------------------------------------------------------
_clone_charts() {
  rm -rf "${CHARTS_DIR}"   # an interrupted clone leaves a half-done folder
  git clone -q --filter=blob:none "${GRADIANT_CHARTS_REPO}" "${CHARTS_DIR}"
}
_fetch_charts_ref() {
  git -C "${CHARTS_DIR}" fetch -q origin "${GRADIANT_CHARTS_REF}" || git -C "${CHARTS_DIR}" fetch -q --tags origin
}

step_charts() {
  step "Charts Gradiant @ ${GRADIANT_CHARTS_REF:0:12}"
  if [[ ! -d "${CHARTS_DIR}/.git" ]]; then
    retry _clone_charts
  fi
  if ! git -C "${CHARTS_DIR}" cat-file -e "${GRADIANT_CHARTS_REF}^{commit}" 2>/dev/null; then
    retry _fetch_charts_ref
  fi
  local head; head=$(git -C "${CHARTS_DIR}" rev-parse HEAD)
  if [[ "${head}" != "$(git -C "${CHARTS_DIR}" rev-parse "${GRADIANT_CHARTS_REF}^{commit}")" ]]; then
    git -C "${CHARTS_DIR}" checkout -q --force "${GRADIANT_CHARTS_REF}"
    rm -f "${CHARTS_DIR}"/charts/*/.deps-ok
  fi
  retry "${HELM_BIN}" repo add bitnami https://charts.bitnami.com/bitnami --force-update >/dev/null
  local c
  for c in open5gs ueransim-gnb; do
    if [[ ! -f "${CHARTS_DIR}/charts/${c}/.deps-ok" ]]; then
      info "helm dependency build ${c}"
      retry "${HELM_BIN}" dependency build "${CHARTS_DIR}/charts/${c}" >/dev/null
      touch "${CHARTS_DIR}/charts/${c}/.deps-ok"
    fi
  done
  ok "open5gs $(awk '/^version:/{print $2}' "${CHARTS_DIR}/charts/open5gs/Chart.yaml") (app $(awk -F'"' '/^appVersion:/{print $2}' "${CHARTS_DIR}/charts/open5gs/Chart.yaml")), ueransim-gnb $(awk '/^version:/{print $2}' "${CHARTS_DIR}/charts/ueransim-gnb/Chart.yaml")"
}

# ----------------------------------------------------------------------------
#  8. Deploy
# ----------------------------------------------------------------------------
# ----------------------------------------------------------------------------
#  7b. Link to the real gNB (RAN_LINK_ENABLED): Multus + ran-link network (macvlan)
# ----------------------------------------------------------------------------
step_ran_link() {
  is_true "${RAN_LINK_ENABLED}" || return 0
  step "Link to the gNB (Multus + macvlan on ${RAN_LINK_IFACE})"
  ip link show "${RAN_LINK_IFACE}" &>/dev/null || die "RAN_LINK_IFACE '${RAN_LINK_IFACE}' does not exist on this host"
  local mtu; mtu=$(cat "/sys/class/net/${RAN_LINK_IFACE}/mtu")
  (( mtu >= RAN_LINK_MTU )) || warn "${RAN_LINK_IFACE} has MTU ${mtu} < RAN_LINK_MTU ${RAN_LINK_MTU}"
  grep -q LOWER_UP < <(ip link show "${RAN_LINK_IFACE}") \
    || warn "${RAN_LINK_IFACE} has no physical link: AMF/UPF/simulated gNB cannot talk until the cable has signal"
  # The rke2-multus chart does not ship the NetworkAttachmentDefinition CRD
  kc apply -f "${PROJECT_DIR}/helm/multus/crd.yaml" >/dev/null
  retry hm upgrade --install multus rke2-multus --repo https://rke2-charts.rancher.io \
    --version "${MULTUS_CHART_VERSION}" --namespace kube-system \
    -f "${PROJECT_DIR}/helm/multus/values.yaml" --wait --timeout 5m >/dev/null
  kc -n kube-system rollout status ds/multus --timeout=180s >/dev/null
  ok "Multus ${MULTUS_CHART_VERSION} ready"
  kc create namespace "${K8S_NAMESPACE}" --dry-run=client -o yaml | kc apply -f - >/dev/null
  render_ran_link_nad
  kc apply -f "${RAN_LINK_NAD}" >/dev/null
  ok "ran-link network: AMF ${AMF_N2_IP}, UPF ${UPF_N3_IP}, simulated gNB ${GNB_SIM_IP} (${RAN_LINK_CIDR}, MTU ${RAN_LINK_MTU})"
}

step_deploy_core() {
  step "Open5GS (release ${OPEN5GS_RELEASE}, namespace ${K8S_NAMESPACE})"
  render_open5gs_values
  info "generated values: ${OPEN5GS_VALUES} (hash ${OPEN5GS_HASH})"
  info "helm upgrade --install (may take several minutes the 1st time: image downloads)"
  # clusterIP is immutable: the old PFCP Service (ClusterIP) must go to become headless
  local cip
  cip=$(kc -n "${K8S_NAMESPACE}" get svc "${OPEN5GS_RELEASE}-upf-pfcp" -o jsonpath='{.spec.clusterIP}' 2>/dev/null || true)
  if [[ -n "${cip}" && "${cip}" != None ]]; then
    kc -n "${K8S_NAMESPACE}" delete svc "${OPEN5GS_RELEASE}-upf-pfcp" >/dev/null
    info "Service ${OPEN5GS_RELEASE}-upf-pfcp (ClusterIP ${cip}) removed: it will be recreated headless"
  fi
  local pr=()
  if is_true "${RAN_LINK_ENABLED}"; then pr=(--post-renderer "${PROJECT_DIR}/helm/postrender/amf-ngap-net1.sh"); fi
  hm upgrade --install "${OPEN5GS_RELEASE}" "${CHARTS_DIR}/charts/open5gs" \
    --namespace "${K8S_NAMESPACE}" --create-namespace \
    -f "${CHARTS_DIR}/charts/open5gs/values-5g.yaml" \
    -f "${OPEN5GS_VALUES}" \
    "${pr[@]}" \
    --wait --timeout "${HELM_TIMEOUT}" >/dev/null \
    || { kc -n "${K8S_NAMESPACE}" get pods; die "Open5GS deploy failed (see the pods above)"; }
  ok "Open5GS deployed"
}

step_subscribers() {
  step "Subscribers (MongoDB)"
  local dep; dep=$(populate_deploy)
  kc -n "${K8S_NAMESPACE}" rollout status "${dep}" --timeout=300s >/dev/null
  sync_subscribers
}

step_deploy_ueransim() {
  if ! is_true "${DEPLOY_UERANSIM}"; then
    step "UERANSIM disabled (DEPLOY_UERANSIM=false)"
    if hm -n "${K8S_NAMESPACE}" status "${UERANSIM_RELEASE}" &>/dev/null; then
      hm -n "${K8S_NAMESPACE}" uninstall "${UERANSIM_RELEASE}" >/dev/null
      ok "release ${UERANSIM_RELEASE} removed"
    fi
    return 0
  fi
  step "UERANSIM gNB + ${UE_COUNT} UE(s) (release ${UERANSIM_RELEASE})"
  render_ueransim_values
  info "generated values: ${UERANSIM_VALUES} (hash ${UERANSIM_HASH})"
  hm upgrade --install "${UERANSIM_RELEASE}" "${CHARTS_DIR}/charts/ueransim-gnb" \
    --namespace "${K8S_NAMESPACE}" \
    -f "${UERANSIM_VALUES}" \
    --post-renderer "${PROJECT_DIR}/helm/postrender/drop-gnb-hpa.sh" \
    --wait --timeout "${HELM_TIMEOUT}" >/dev/null \
    || { kc -n "${K8S_NAMESPACE}" get pods; die "UERANSIM deploy failed"; }
  ok "UERANSIM deployed"
  ensure_user_plane || warn "the user plane is not OK — run ./test.sh -v"
}

# ----------------------------------------------------------------------------
#  8a. Dashboard (Innova Center Dashboard) — docs/components/dashboard.md
#  Read-only pod in the core namespace + (optional) gNB log agent, which
#  runs on THIS machine as the install user and reads the log over SSH (tail -F).
# ----------------------------------------------------------------------------
dashboard_firewall() {
  is_true "${DASHBOARD_ENABLED}" || return 0
  if ${UFW_ACTIVE} && is_true "${CONFIGURE_UFW}"; then
    ufw allow "${DASHBOARD_NODEPORT}/tcp" comment 'open5gs-k3s dashboard' >/dev/null
  fi
  if ${HAS_FIREWALLD} && is_true "${CONFIGURE_FIREWALLD}"; then
    firewall-cmd -q --permanent --add-port="${DASHBOARD_NODEPORT}/tcp" 2>/dev/null && firewall-cmd -q --reload || true
  fi
}

# Settings tab: administrator password (generated once, only root reads it) and permissions
dashboard_config_edit() {
  DASHBOARD_ADMIN_PASSWORD="" DASHBOARD_CONFIG_GID=""
  is_true "${DASHBOARD_CONFIG_EDIT}" || return 0
  local cfg="${PROJECT_DIR}/config.env" pwf="${INSTALL_DIR}/state/dashboard-admin-password" gid
  if [[ "$(readlink -f "${CONFIG}")" != "$(readlink -f "${cfg}")" ]]; then
    warn "Settings tab off: it only edits ${cfg} (CONFIG points to ${CONFIG})"; return 0
  fi
  if [[ ! -s "${pwf}" ]]; then
    install -m 0600 -o root -g root /dev/null "${pwf}"
    head -c 32 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | cut -c1-20 >"${pwf}"
  fi
  DASHBOARD_ADMIN_PASSWORD=$(<"${pwf}")
  gid=$(stat -c %g "${cfg}")
  if (( gid == 0 )); then warn "Settings tab off: ${cfg} belongs to the root group"; DASHBOARD_ADMIN_PASSWORD=""; return 0; fi
  # The pod (user 65534) writes through the group of the file owner: needs g+w
  [[ $(( 0$(stat -c %a "${cfg}") & 020 )) -ne 0 ]] || { chmod g+w "${cfg}"; info "config.env: group write permission (Settings tab)"; }
  install -d -m 2770 -o root -g "${gid}" "${INSTALL_DIR}/state/config-backups"
  DASHBOARD_CONFIG_GID="${gid}"
}

step_dashboard() {
  if ! is_true "${DASHBOARD_ENABLED}"; then
    if kc -n "${K8S_NAMESPACE}" get deploy dashboard &>/dev/null; then
      kc -n "${K8S_NAMESPACE}" delete deploy,svc,configmap/dashboard-app,secret,sa dashboard --ignore-not-found >/dev/null 2>&1 || true
      kc -n "${K8S_NAMESPACE}" delete role,rolebinding dashboard-read --ignore-not-found >/dev/null 2>&1 || true
      ok "dashboard removed (DASHBOARD_ENABLED=false)"
    fi
    remove_gnb_log_agent
    remove_hosts_agent
    remove_ru_agent
    remove_gnb_ctl_agent
    return 0
  fi
  step "Innova Center Dashboard (NodePort ${DASHBOARD_NODEPORT})"
  # gNB log agent token: generated once and kept for root only
  local tokf="${INSTALL_DIR}/state/dashboard-ingest-token"
  if [[ ! -s "${tokf}" ]]; then
    install -m 0600 -o root -g root /dev/null "${tokf}"
    head -c 32 /dev/urandom | sha256sum | cut -c1-48 >"${tokf}"
  fi
  DASHBOARD_INGEST_TOKEN=$(<"${tokf}")
  dashboard_config_edit
  # Persistent history: pod folder (user 65534); stays on the host even with the dashboard off
  if is_true "${DASHBOARD_PERSIST}"; then
    install -d -m 0750 -o 65534 -g 65534 "${DASHBOARD_DATA_DIR}"
    info "persistent history in ${DASHBOARD_DATA_DIR} (retention ${DASHBOARD_PERSIST_DAYS} days, max. ${DASHBOARD_PERSIST_MAX_GB} GB)"
  fi
  kc create namespace "${K8S_NAMESPACE}" --dry-run=client -o yaml | kc apply -f - >/dev/null
  render_dashboard
  # server-side: the dashboard files exceed 256 KB (limit of the last-applied annotation of a plain apply)
  kc apply --server-side --force-conflicts --field-manager=open5gk3s -f "${DASHBOARD_MANIFEST}" >/dev/null
  kc -n "${K8S_NAMESPACE}" rollout status deploy/dashboard --timeout=300s >/dev/null \
    || { kc -n "${K8S_NAMESPACE}" get pods -l app.kubernetes.io/name=dashboard; die "the dashboard did not become ready"; }
  dashboard_firewall
  ok "dashboard up: http://${NODE_IP:-localhost}:${DASHBOARD_NODEPORT}"
  if [[ -n "${GNB_METRICS_URL}" ]]; then info "gNB metrics: ${GNB_METRICS_URL}"; fi
  setup_gnb_log_agent
  setup_hosts_agent
  setup_ru_agent
  setup_gnb_ctl_agent
}

