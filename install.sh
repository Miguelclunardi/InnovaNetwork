# OCUDU gNB from the Control tab: the agent reads the gNB state (k8s pod or the ocudu-gnb@ service on
# the gNB host) and runs start/stop (gnb.sh, or systemctl authorized by polkit there). Same SSH key as the log.
setup_gnb_ctl_agent() {
  if ! is_true "${DASHBOARD_CONTROL}" || [[ -z "${GNB_CTL_SSH}" ]]; then remove_gnb_ctl_agent; return 0; fi
  [[ "${TARGET_USER}" != root ]] || { warn "the gNB control agent needs a regular user"; return 0; }
  local dst="${INSTALL_DIR}/dashboard-agent" unit
  install -d -m 0755 -o root -g root "${dst}"
  install -m 0755 -o root -g root "${PROJECT_DIR}/dashboard/agent/gnb-ctl-agent.py" "${dst}/gnb-ctl-agent.py"
  install -m 0640 -o root -g "${TARGET_GROUP}" /dev/null "${dst}/gnb-ctl.env"
  {
    echo "DASHBOARD_URL=http://${K3S_NODE_IP:-127.0.0.1}:${DASHBOARD_NODEPORT}"  # fixed node IP: does not change with DHCP
    echo "INGEST_TOKEN=${DASHBOARD_INGEST_TOKEN}"
    echo "GNB_CTL_SSH=${GNB_CTL_SSH}"
    echo "GNB_CTL_DIR=${GNB_CTL_DIR}"
    echo "GNB_CTL_MODE=${GNB_CTL_MODE}"
    if [[ "${GNB_CTL_MODE}" == k8s ]]; then
      echo "GNB_CTL_GNBSH=${PROJECT_DIR}/ran/ocudu/gnb.sh"
      echo "KUBECONFIG=${TARGET_HOME}/.kube/config"
    fi
  } >"${dst}/gnb-ctl.env"
  unit=$(cat <<EOU
# Gerado por open5GK3S/install.sh
[Unit]
Description=InnovaNetwork: start/stop the OCUDU gNB (${GNB_CTL_SSH}) from the dashboard
After=network-online.target k3s.service
Wants=network-online.target

[Service]
Type=simple
User=${TARGET_USER}
EnvironmentFile=${dst}/gnb-ctl.env
ExecStart=/usr/bin/python3 -u ${dst}/gnb-ctl-agent.py
Restart=always
RestartSec=10
NoNewPrivileges=true

[Install]
WantedBy=multi-user.target
EOU
)
  if [[ "$(cat "${GNBCTL_UNIT_FILE}" 2>/dev/null)" != "${unit}" ]]; then
    printf '%s\n' "${unit}" >"${GNBCTL_UNIT_FILE}"; systemctl daemon-reload
  fi
  systemctl enable open5gs-k3s-gnb-ctl.service >/dev/null 2>&1
  systemctl restart open5gs-k3s-gnb-ctl.service
  if [[ "${GNB_CTL_MODE}" == k8s ]]; then
    if su - "${TARGET_USER}" -s /bin/bash -c "KUBECONFIG=${TARGET_HOME}/.kube/config kubectl -n ocudu get deploy ocudu-gnb" &>/dev/null; then
      ok "Control tab: OCUDU gNB on Kubernetes (pod ocudu-gnb; journalctl -u open5gs-k3s-gnb-ctl)"
    else
      warn "Control tab: the ocudu-gnb Deployment does not exist: install OCUDU (docs/installation.md, ran/ocudu/install.sh)"
    fi
  elif su - "${TARGET_USER}" -s /bin/bash -c "ssh -o BatchMode=yes -o ConnectTimeout=5 ${GNB_CTL_SSH} test -f /etc/systemd/system/ocudu-gnb@.service" &>/dev/null; then
    ok "Control tab: OCUDU gNB controllable (${GNB_CTL_SSH}; journalctl -u open5gs-k3s-gnb-ctl)"
  else
    warn "Control tab: the gNB service is not installed on the gNB host (once, with sudo there):"
    warn "  scp scripts/ocudu/setup-gnb-service.sh ${GNB_CTL_SSH}:/tmp/ && ssh -t ${GNB_CTL_SSH} sudo bash /tmp/setup-gnb-service.sh --dir ${GNB_CTL_DIR}"
  fi
}

