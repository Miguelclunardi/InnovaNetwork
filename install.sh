# ----------------------------------------------------------------------------
#  8b. Automatic recovery at boot (AUTO_HEAL)
#  After a reboot the pods come back in any order and the user plane
#  may get out of sync (UPF/SMF/UE). The unit runs scripts/heal.sh at every boot.
#  It runs as root, so it executes a COPY in ${INSTALL_DIR} (owned by root),
#  never the user's editable project files.
# ----------------------------------------------------------------------------
step_boot_heal() {
  step "Boot: CORE_AUTOSTART=${CORE_AUTOSTART}, AUTO_HEAL=${AUTO_HEAL}"
  local mode="--boot" desc="checks and recovers the user plane after boot"
  if ! is_true "${CORE_AUTOSTART}"; then
    mode="--boot-off"; desc="stops the core at boot (start it from the dashboard Control tab)"
  fi
  if ! is_true "${AUTO_HEAL}" && is_true "${CORE_AUTOSTART}"; then
    if [[ -f "${HEAL_UNIT_FILE}" ]]; then
      systemctl disable open5gs-k3s-heal.service >/dev/null 2>&1 || true
      rm -f "${HEAL_UNIT_FILE}"; systemctl daemon-reload
      ok "unit open5gs-k3s-heal removed"
    else
      info "off; after a reboot run ./scripts/heal.sh if ./test.sh fails"
    fi
    return 0
  fi
  local dst="${INSTALL_DIR}/heal" unit
  install -d -m 0755 -o root -g root "${dst}" "${dst}/scripts" "${dst}/scripts/lib"
  install -m 0755 -o root -g root "${PROJECT_DIR}/scripts/heal.sh" "${dst}/scripts/heal.sh"
  install -m 0644 -o root -g root "${PROJECT_DIR}/scripts/lib/common.sh" "${dst}/scripts/lib/common.sh"
  install -m 0600 -o root -g root "${CONFIG}" "${dst}/config.env"
  unit=$(cat <<EOU
# Gerado por open5GK3S/install.sh
[Unit]
Description=InnovaNetwork: ${desc}
After=k3s.service
Wants=k3s.service

[Service]
# exec (not oneshot): does not delay the boot while waiting for the pods
Type=exec
Environment=CONFIG=${dst}/config.env HOME=/root
ExecStart=${dst}/scripts/heal.sh ${mode}

[Install]
WantedBy=multi-user.target
EOU
)
  if [[ "$(cat "${HEAL_UNIT_FILE}" 2>/dev/null)" != "${unit}" ]]; then
    printf '%s\n' "${unit}" >"${HEAL_UNIT_FILE}"; systemctl daemon-reload
  fi
  systemctl enable open5gs-k3s-heal.service >/dev/null 2>&1
  if [[ "${mode}" == --boot-off ]]; then
    ok "at boot the core stays STOPPED (CORE_AUTOSTART=false): start it from the Control tab (log: journalctl -u open5gs-k3s-heal)"
  else
    ok "unit open5gs-k3s-heal active at boot (copy in ${dst}; log: journalctl -u open5gs-k3s-heal)"
  fi
}

