#!/usr/bin/env bash
# =============================================================================
#  ran/ocudu/install.sh — OCUDU gNB on Kubernetes (RAN component of InnovaNetwork).
#
#  Runs on the core machine (k3s server). Separate from the install.sh of the cores and dashboard.
#  DEPENDS ON YOUR SETUP: see ran/ocudu/ocudu.env and docs/components/ocudu.md.
#
#  Order, the first time:
#    1. ./ran/ocudu/install.sh copy            copies no-ran.sh + ocudu.env to the node (~/innovanetwork-ran)
#    2. on the node: sudo ~/innovanetwork-ran/no-ran.sh image   (builds the gNB image)
#    3. sudo ./ran/ocudu/install.sh prepare    opens the server UFW to the node and sends the node a join
#                                              token (valid 2 h; never shown on the screen)
#    4. on the node: sudo ~/innovanetwork-ran/no-ran.sh join    (k3s agent; imports the image)
#    5. ./ran/ocudu/install.sh                 creates the namespace and the Deployment (0 replicas = stopped)
#    6. ./ran/ocudu/gnb.sh start [yml]         starts the gNB (the native service must be stopped)
#
#  Other options:  --dry-run (generates and validates on the server; does not apply) · --remove (deletes
#  the namespace). The Portuguese names of earlier versions (copiar, preparar, --remover) still work.
# =============================================================================
set -Eeuo pipefail
OC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "${OC_DIR}/../.." && pwd)"
# shellcheck source=../../scripts/lib/common.sh
source "${PROJECT_DIR}/scripts/lib/common.sh"
load_config
# shellcheck source=ocudu.env
source "${OC_DIR}/ocudu.env"
unset HELM_CACHE_HOME HELM_CONFIG_HOME HELM_DATA_HOME
KUBECTL="kubectl"
[[ $EUID -ne 0 ]] || KUBECTL="kubectl --kubeconfig ${KUBECONFIG_PATH:-/etc/rancher/k3s/k3s.yaml}"
k() { ${KUBECTL} "$@"; }
OWNER="${SUDO_USER:-$(id -un)}"
as_owner() { if [[ $EUID -eq 0 && -n "${SUDO_USER:-}" ]]; then sudo -u "${SUDO_USER}" "$@"; else "$@"; fi; }
NODE_DIR="innovanetwork-ran"           # in the home of the node user

copy_to_node() {  # $@ = local files
  step "Copying to ${OCUDU_NODE_SSH}:~/${NODE_DIR}/"
  as_owner ssh -o BatchMode=yes "${OCUDU_NODE_SSH}" "mkdir -p ~/${NODE_DIR} && chmod 700 ~/${NODE_DIR}"
  as_owner scp -q -o BatchMode=yes "$@" "${OCUDU_NODE_SSH}:${NODE_DIR}/"
  as_owner ssh -o BatchMode=yes "${OCUDU_NODE_SSH}" "chmod 700 ~/${NODE_DIR}/no-ran.sh; chmod 600 ~/${NODE_DIR}/*.env"
  ok "$(printf '%s ' "${@##*/}")"
}

do_copy() {
  copy_to_node "${OC_DIR}/no-ran.sh" "${OC_DIR}/ocudu.env"
  info "on the node: sudo ~/${NODE_DIR}/no-ran.sh image   (then: prepare + join)"
}

do_prepare() {
  [[ $EUID -eq 0 ]] || die "run with sudo: sudo $0 prepare"
  [[ "${NODE_IP_MODE}" == "stable" ]] || die "this join mode uses NODE_IP_MODE=stable (server on ${STABLE_IP})"
  if ufw status 2>/dev/null | grep -q "Status: active"; then
    step "Server UFW: opening for the node ${OCUDU_NODE_IP}"
    ufw allow from "${OCUDU_NODE_IP}" comment 'InnovaNetwork k3s RAN node' >/dev/null
    ufw allow from 10.42.0.0/16 comment 'InnovaNetwork k3s pods' >/dev/null
    ufw allow from 10.43.0.0/16 comment 'InnovaNetwork k3s services' >/dev/null
    ok "rules 'InnovaNetwork k3s'"
  fi
  step "Join token (2 h) for the node"
  local tmp; tmp="$(mktemp -d)"; chmod 700 "${tmp}"
  local tok; tok="$(k3s token create --ttl 2h --description "InnovaNetwork RAN node ${OCUDU_NODE}")"
  [[ -n "${tok}" ]] || die "k3s token create returned no token"
  umask 077
  cat > "${tmp}/join.env" <<EOF
# Generated by ran/ocudu/install.sh prepare ($(date -Is)). Deleted by no-ran.sh join.
K3S_URL="https://${STABLE_IP}:6443"
K3S_TOKEN="${tok}"
K3S_VERSION="${K3S_VERSION}"
STABLE_IP="${STABLE_IP}"
EOF
  chown -R "${OWNER}" "${tmp}"
  copy_to_node "${OC_DIR}/no-ran.sh" "${OC_DIR}/ocudu.env" "${tmp}/join.env"
  rm -rf "${tmp}"
  info "on the node: sudo ~/${NODE_DIR}/no-ran.sh join"
}

image_tag() {
  if [[ -n "${OCUDU_IMAGE_TAG}" ]]; then echo "${OCUDU_IMAGE_TAG}"; return; fi
  as_owner ssh -o BatchMode=yes "${OCUDU_NODE_SSH}" "git -C '${OCUDU_SRC_DIR}' rev-parse --short=7 HEAD"
}

render() {  # $1 = image tag; $2 = .yml in use; $3 = replicas; $4 = time of the last start request
  OCUDU_IMAGE_TAG="$1" OCUDU_GNB_CONFIG="$2" OCUDU_REPLICAS="$3" OCUDU_START_REQUEST="${4:-0}" OCUDU_NAMESPACE="${OCUDU_NAMESPACE}" OCUDU_NODE="${OCUDU_NODE}" \
  OCUDU_CONFIG_DIR="${OCUDU_CONFIG_DIR}" OCUDU_LOG_DIR="${OCUDU_LOG_DIR}" OCUDU_IMAGE="${OCUDU_IMAGE}" \
  OCUDU_DEFAULT_CONFIG="${OCUDU_DEFAULT_CONFIG}" OCUDU_EXTRA_CONFIG="${OCUDU_EXTRA_CONFIG}" \
  OCUDU_CPUS="${OCUDU_CPUS}" OCUDU_AUX_CPUS="${OCUDU_AUX_CPUS:-}" OCUDU_HUGEPAGES_1G="${OCUDU_HUGEPAGES_1G}" \
  OCUDU_MEMORY_REQUEST="${OCUDU_MEMORY_REQUEST}" python3 "${OC_DIR}/lib/render.py"
}

do_deploy() {
  local dry="$1" tag out
  tag="$(image_tag)"; [[ -n "${tag}" ]] || die "could not read the OCUDU commit on the node"
  out="${GENERATED_DIR}/ocudu"; mkdir -p "${out}"
  step "Manifests (image ${OCUDU_IMAGE}:${tag})"
  # If it already exists, keep the replicas and the chosen .yml (do not take down a running gNB)
  local cur_rep cur_cfg
  cur_rep="$(k -n "${OCUDU_NAMESPACE}" get deploy ocudu-gnb -o jsonpath='{.spec.replicas}' 2>/dev/null || true)"
  cur_cfg="$(k -n "${OCUDU_NAMESPACE}" get deploy ocudu-gnb -o jsonpath='{.spec.template.spec.containers[0].env[?(@.name=="GNB_CONFIG")].value}' 2>/dev/null || true)"
  local cur_req
  cur_req="$(k -n "${OCUDU_NAMESPACE}" get deploy ocudu-gnb -o jsonpath='{.spec.template.spec.containers[0].env[?(@.name=="GNB_START_REQUEST")].value}' 2>/dev/null || true)"
  # gNB running and still without the variable (earlier version): count it as requested now, so it does not stay stopped
  if [[ -z "${cur_req}" && "${cur_rep:-0}" != "0" ]]; then cur_req="$(date +%s)"; fi
  render "${tag}" "${cur_cfg:-${OCUDU_DEFAULT_CONFIG}}" "${cur_rep:-0}" "${cur_req:-0}" > "${out}/ocudu.yaml"
  ok "${out}/ocudu.yaml"
  if ${dry}; then
    # client: the namespace may not exist yet (the server would refuse the Deployment)
    k apply --dry-run=client -f "${out}/ocudu.yaml" | sed 's/^/    /'
    if k get namespace "${OCUDU_NAMESPACE}" >/dev/null 2>&1; then
      k apply --dry-run=server -f "${out}/ocudu.yaml" | sed 's/^/    /'
    fi
    return
  fi
  step "Node ${OCUDU_NODE}"
  k get node "${OCUDU_NODE}" >/dev/null 2>&1 || die "node ${OCUDU_NODE} is not in the cluster (steps 3 and 4)"
  k get node "${OCUDU_NODE}" -o jsonpath='{.status.conditions[?(@.type=="Ready")].status}' | grep -q True \
    || die "node ${OCUDU_NODE} is not Ready"
  k get node "${OCUDU_NODE}" -o jsonpath='{range .status.images[*]}{.names}{"\n"}{end}' \
    | grep -qF "${OCUDU_IMAGE}:${tag}" || warn "image ${OCUDU_IMAGE}:${tag} does not show on the node (on the node: no-ran.sh import)"
  ok "Ready"
  step "Applying (current replicas: ${cur_rep:-0}; 0 = gNB stopped)"
  k apply -f "${out}/ocudu.yaml" | sed 's/^/    /'
  ok "gNB: ./ran/ocudu/gnb.sh start [yml] | stop | status | log"
}

case "${1:-}" in
  copy|copiar)        do_copy ;;
  prepare|preparar)   do_prepare ;;
  --dry-run)          do_deploy true ;;
  --remove|--remover) k delete namespace "${OCUDU_NAMESPACE}" --ignore-not-found ;;
  "")                 do_deploy false ;;
  -h|--help)          sed -n '2,19p' "$0" | sed 's/^# \{0,1\}//' ;;
  *)                  die "unknown option: $1 (see --help)" ;;
esac
